// The host firewall (apps probe 2.1): the iptables-save parser, the ruleset hash two identical boxes share, and the rows per box.
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), "advisor-firewall-test-"));
process.env.TYPESAFE_API_KEY = "";

const hf = await import("../host_firewall.js");
const { db } = await import("../db.js");
const one = (sql: string): any => db.prepare(sql).get();

/** A Docker host as iptables-save prints it, timestamps and counters included (the probe strips them; the parser tolerates them). */
export const DOCKER_HOST = `# Generated by iptables-save v1.8.7 on Sat Nov  1 10:00:00 2026
*filter
:INPUT DROP [12:3456]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [99:1000]
:DOCKER - [0:0]
:DOCKER-USER - [0:0]
:BOTH - [0:0]
-A INPUT -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A INPUT -i lo -j ACCEPT
-A INPUT -p tcp -m tcp --dport 22 -m comment --comment "allow \\"office\\" ssh" -j ACCEPT
-A INPUT -p tcp -m multiport --dports 80,443,8000:8100 -j ACCEPT
-A INPUT ! -s 10.0.0.0/8 -p tcp -m tcp --dport 5432 -j DROP
-A INPUT -s 203.0.113.0/24 -j BOTH
-A INPUT -j REJECT --reject-with icmp-host-prohibited
-A FORWARD -j DOCKER-USER
-A FORWARD -j BOTH
-A FORWARD -j DOCKER
-A OUTPUT -d 198.51.100.7/32 -p udp -m udp --dport 53 -j ACCEPT
-A DOCKER -d 172.17.0.2/32 ! -i docker0 -o docker0 -p tcp -m tcp --dport 80 -j ACCEPT
-A DOCKER-USER -j RETURN
-A BOTH -p icmp -j LOG --log-prefix "both: "
COMMIT
# Completed on Sat Nov  1 10:00:00 2026
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
:DOCKER - [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER
-A POSTROUTING -s 172.17.0.0/16 ! -o docker0 -j MASQUERADE
-A DOCKER ! -i docker0 -p tcp -m tcp --dport 8080 -j DNAT --to-destination 172.17.0.2:80
COMMIT
*mangle
:PREROUTING ACCEPT [0:0]
-A PREROUTING -j TTL --ttl-set 64
COMMIT`.split("\n");
const V6 = ["*filter", ":INPUT ACCEPT [0:0]", ":FORWARD ACCEPT [0:0]", ":OUTPUT ACCEPT [0:0]", "-A INPUT -s ::/0 -p tcp -m tcp --dport 22 -j ACCEPT", "COMMIT"];
const probe = (v4: string[], v6: string[] = [], extra: Partial<import("../ssm.js").ProbeFirewall> = {}): import("../ssm.js").ProbeFirewall => ({ available: true, backend: "nf_tables", v4, v6, nft: [], v4_lines: v4.length, v6_lines: v6.length, nft_lines: 0, oversize: false, ...extra });

test("tokenize keeps a quoted comment whole, escapes and all", () => {
  assert.deepEqual(hf.tokenize('-A INPUT -m comment --comment "allow \\"office\\" ssh" -j ACCEPT'), ["-A", "INPUT", "-m", "comment", "--comment", 'allow "office" ssh', "-j", "ACCEPT"]);
  assert.deepEqual(hf.tokenize("-A INPUT  -j  DROP"), ["-A", "INPUT", "-j", "DROP"]);
});

test("parseIptablesSave: tables, chains and policies, every option the rules carry, negation, the comment, the target and its arguments", () => {
  const { chains, rules } = hf.parseIptablesSave(DOCKER_HOST, "ipv4");
  assert.deepEqual(chains.filter((c) => c.table === "filter").map((c) => [c.name, c.policy, c.builtin, c.rules]), [["INPUT", "DROP", true, 7], ["FORWARD", "ACCEPT", true, 3], ["OUTPUT", "ACCEPT", true, 1], ["DOCKER", null, false, 1], ["DOCKER-USER", null, false, 1], ["BOTH", null, false, 1]]);
  const input = rules.filter((r) => r.table === "filter" && r.chain === "INPUT");
  assert.deepEqual(input.map((r) => r.index), [0, 1, 2, 3, 4, 5, 6], "priority is the position in the chain");
  assert.deepEqual(input[0].states, ["RELATED", "ESTABLISHED"]); assert.equal(input[0].action, "allow"); assert.equal(input[0].protocol, "any"); assert.equal(input[0].direction, "ingress");
  assert.equal(input[1].in_interface, "lo");
  assert.equal(input[2].protocol, "tcp"); assert.equal(input[2].from_port, 22); assert.equal(input[2].to_port, 22); assert.equal(input[2].comment, 'allow "office" ssh');
  assert.equal(input[2].raw, "-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT", "the comment module is not part of the raw line");
  assert.equal(input[3].ports, "80,443,8000:8100"); assert.equal(input[3].from_port, 80); assert.equal(input[3].to_port, 80);
  assert.equal(input[4].source, "10.0.0.0/8"); assert.equal(input[4].source_negated, true); assert.equal(input[4].action, "deny"); assert.equal(input[4].target, "DROP");
  assert.equal(input[5].action, "jump"); assert.equal(input[5].target, "BOTH"); assert.equal(input[5].source, "203.0.113.0/24"); assert.equal(input[5].source_negated, false);
  assert.equal(input[6].action, "deny"); assert.equal(input[6].target, "REJECT"); assert.equal(input[6].target_args, "--reject-with icmp-host-prohibited");
  const out = rules.find((r) => r.chain === "OUTPUT")!;
  assert.equal(out.direction, "egress"); assert.equal(out.destination, "198.51.100.7/32"); assert.equal(out.protocol, "udp"); assert.equal(out.from_port, 53);
  const docker = rules.find((r) => r.table === "filter" && r.chain === "DOCKER")!;
  assert.equal(docker.direction, "forward", "jumped to from FORWARD only"); assert.equal(docker.in_interface, "!docker0"); assert.equal(docker.out_interface, "docker0"); assert.equal(docker.destination, "172.17.0.2/32");
  assert.equal(rules.find((r) => r.chain === "DOCKER-USER")!.action, "return");
  const both = rules.find((r) => r.chain === "BOTH")!;
  assert.equal(both.direction, "chain", "reached from INPUT and FORWARD: no single direction"); assert.equal(both.action, "log"); assert.equal(both.target_args, "--log-prefix both: ", "the argument as written, trailing space included");
  const dnat = rules.find((r) => r.target === "DNAT")!;
  assert.equal(dnat.table, "nat"); assert.equal(dnat.action, "nat"); assert.equal(dnat.direction, "ingress", "the nat DOCKER chain hangs off PREROUTING"); assert.equal(dnat.from_port, 8080); assert.equal(dnat.target_args, "--to-destination 172.17.0.2:80");
  assert.equal(rules.find((r) => r.target === "MASQUERADE")!.action, "nat");
  assert.equal(rules.find((r) => r.target === "TTL")!.action, "other");
  assert.equal(hf.effectiveDefault(chains, rules), "deny");
});

test("isGraphRule and the normalized text: the filter table and the nat port publishing go in, mangle and masquerade stay out, comments and counters never count", () => {
  const { chains, rules } = hf.parseIptablesSave(DOCKER_HOST, "ipv4");
  assert.deepEqual(rules.filter(hf.isGraphRule).map((r) => `${r.table}/${r.target}`).filter((x, i, a) => a.indexOf(x) === i), ["filter/ACCEPT", "filter/DROP", "filter/BOTH", "filter/REJECT", "filter/DOCKER-USER", "filter/DOCKER", "filter/RETURN", "filter/LOG", "nat/DNAT"]);
  const text = hf.normalizedText(chains, rules);
  assert.ok(text.startsWith("ipv4 filter :INPUT DROP\nipv4 filter :FORWARD ACCEPT\nipv4 filter :OUTPUT ACCEPT\nipv4 filter -A INPUT -m conntrack"), text.slice(0, 200));
  assert.ok(!text.includes("comment") && !text.includes("MASQUERADE") && !text.includes("TTL") && !text.includes("[12:3456]"));
});

test("effectiveDefault: an ACCEPT policy with a trailing catch-all REJECT is deny; a bare ACCEPT policy is allow", () => {
  const rhel = hf.parseIptablesSave(["*filter", ":INPUT ACCEPT [0:0]", ":FORWARD ACCEPT [0:0]", ":OUTPUT ACCEPT [0:0]", "-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT", "-A INPUT -j REJECT --reject-with icmp-host-prohibited", "COMMIT"], "ipv4");
  assert.equal(hf.effectiveDefault(rhel.chains, rhel.rules), "deny");
  const open = hf.parseIptablesSave(["*filter", ":INPUT ACCEPT [0:0]", "-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT", "COMMIT"], "ipv4");
  assert.equal(hf.effectiveDefault(open.chains, open.rules), "allow");
});

test("rulesetOf: the id is the hash of the rules alone, so two boxes with the same rules share it whatever their comments, counters or timestamps; a different rule, order or family is another ruleset", () => {
  const a = hf.rulesetOf(probe(DOCKER_HOST))!;
  assert.ok(/^hostfw:[0-9a-f]{64}$/.test(a.id));
  assert.equal(a.rule_count, 18); assert.equal(a.graph_rules, 15); assert.deepEqual(a.tables, { filter: 14, nat: 3, mangle: 1 });
  assert.equal(a.default_action, "deny"); assert.equal(a.input_policy, "DROP"); assert.equal(a.forward_policy, "ACCEPT"); assert.equal(a.truncated, false); assert.equal(a.backend, "nf_tables");
  const cleaned = DOCKER_HOST.filter((l) => !l.startsWith("#")).map((l) => l.replace(/ \[\d+:\d+\]$/, "").replace('allow \\"office\\" ssh', "other words"));
  assert.equal(hf.rulesetOf(probe(cleaned))!.id, a.id, "what the probe prints (no counters, no timestamps) and a different comment: the same ruleset");
  assert.equal(hf.rulesetOf(probe(cleaned, [], { backend: "legacy" }))!.id, a.id, "the backend is not part of the id");
  assert.notEqual(hf.rulesetOf(probe(DOCKER_HOST.map((l) => l.replace("--dport 22", "--dport 2222"))))!.id, a.id, "a changed port");
  const swapped = [...DOCKER_HOST]; const i = swapped.indexOf("-A INPUT -i lo -j ACCEPT"); [swapped[i], swapped[i + 1]] = [swapped[i + 1], swapped[i]];
  assert.notEqual(hf.rulesetOf(probe(swapped))!.id, a.id, "order is evaluation order");
  assert.notEqual(hf.rulesetOf(probe(DOCKER_HOST, V6))!.id, a.id, "IPv6 rules are part of it");
  assert.equal(hf.rulesetOf(probe(DOCKER_HOST.map((l) => l.replace("-j TTL --ttl-set 64", "-j TTL --ttl-set 63"))))!.id, a.id, "mangle is counted, not hashed");
  assert.equal(hf.rulesetOf(probe(DOCKER_HOST, [], { v4_lines: 500 }))!.truncated, true, "the probe cut the text");
  assert.equal(hf.rulesetOf(probe([], [], { available: false })), null, "no tool");
  assert.equal(hf.rulesetOf(probe([], [])), null, "a tool with no tables loaded");
  const nft = hf.rulesetOf(probe([], [], { backend: "nftables", nft: ["table inet filter {", "chain input {", "type filter hook input priority 0; policy drop;", "tcp dport 22 accept", "}", "}"], nft_lines: 6 }))!;
  assert.equal(nft.rules.length, 0); assert.ok(nft.id.startsWith("hostfw:")); assert.equal(nft.default_action, "allow", "no iptables chains to read a policy from");
});

test("recordHostFirewall: the first probe is silent, the same rules again change nothing, a changed ruleset is a firewall_changed event, two boxes with the same rules share one ruleset row, a box without a filter has none", () => {
  const at = (n: number) => `2026-11-01T1${n}:00:00Z`;
  const a = hf.recordHostFirewall("i-fw1", at(0), { firewall: probe(DOCKER_HOST) })!;
  assert.equal(a.changed, false); assert.ok(a.ruleset_id!.startsWith("hostfw:")); assert.equal(a.rules, 18);
  const b = hf.recordHostFirewall("i-fw1", at(1), { firewall: probe(DOCKER_HOST.filter((l) => !l.startsWith("#"))) })!;
  assert.equal(b.changed, false); assert.equal(b.ruleset_id, a.ruleset_id);
  assert.equal(one("select count(*) as n from firewall_rulesets").n, 1);
  assert.equal(one("select probes from instance_firewall where instance_id = 'i-fw1'").probes, 2);
  assert.equal(one("select count(*) as n from instance_app_events where instance_id = 'i-fw1'").n, 0, "nothing changed, no event");
  const c = hf.recordHostFirewall("i-fw1", at(2), { firewall: probe(DOCKER_HOST.map((l) => l.replace("--dport 22", "--dport 2222"))) })!;
  assert.equal(c.changed, true); assert.equal(c.previous, a.ruleset_id); assert.notEqual(c.ruleset_id, a.ruleset_id);
  const ev = db.prepare("select name, user, event, details from instance_app_events where instance_id = 'i-fw1'").all() as any[];
  assert.equal(ev.length, 1); assert.equal(ev[0].event, "firewall_changed"); assert.equal(ev[0].name, "firewall");
  assert.deepEqual(JSON.parse(ev[0].details), { from: a.ruleset_id, to: c.ruleset_id, rules_from: 18, rules_to: 18, available: true, backend: "nf_tables" });
  assert.equal(one("select changed_at from instance_firewall where instance_id = 'i-fw1'").changed_at, at(2));
  const d = hf.recordHostFirewall("i-fw2", at(3), { firewall: probe(DOCKER_HOST) })!;
  assert.equal(d.ruleset_id, a.ruleset_id, "the second box wears the first box's old ruleset: one row");
  assert.equal(one("select count(*) as n from firewall_rulesets").n, 2);
  assert.deepEqual([...hf.rulesetAttachments().entries()].sort(), [[a.ruleset_id, 1], [c.ruleset_id, 1]].sort());
  const e = hf.recordHostFirewall("i-fw3", at(4), { firewall: probe([], [], { available: false, backend: null }) })!;
  assert.equal(e.ruleset_id, null); assert.equal(e.available, false);
  assert.equal(hf.recordHostFirewall("i-fw3", at(5), {}), null, "an older document prints no section: nothing to record");
  const gone = hf.recordHostFirewall("i-fw2", at(6), { firewall: probe([], [], { available: false }) })!;
  assert.equal(gone.changed, true); assert.equal(gone.previous, a.ruleset_id); assert.equal(gone.ruleset_id, null, "the filter went away: an event, a bare row");
  const stored = hf.firewallOn("i-fw1")!;
  assert.equal(stored.ruleset?.id, c.ruleset_id); assert.equal(stored.ruleset?.rules.length, 18); assert.ok(stored.raw_v4!.includes("--dport 2222"));
  assert.deepEqual(hf.instanceFirewalls(["i-fw1", "i-fw3"]).map((r) => [r.instance_id, r.ruleset_id != null, r.available]), [["i-fw1", true, true], ["i-fw3", false, false]]);
  assert.equal(hf.rulesetById("hostfw:nope"), null);
});
